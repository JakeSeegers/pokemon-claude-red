// Builds src/data/dxcases.js (the STUDY CASES encounters, src/game/dxcases.js) from the Data section of the
// diagnosis-practice-case skill: a condensed study summary of the DSM-5-TR differential diagnosis tables.
//   node tools/convert_dx.js <path to SKILL.md>
// Each table: roll number, table id, name, optional members, core features, and differentials (name: rule-out clue).
// Sexual Dysfunctions and Paraphilic Disorders go into a separate list, G.DX_ADULT_TABLES: the skill allows them only
// as adult, unthemed, clinical cases, so the game uses them only with OPTION > ADULT CASES, never with the theme.
const fs = require('fs'), path = require('path');
const src = fs.readFileSync(process.argv[2], 'utf8');
const data = src.slice(src.indexOf('## Data'));
const SKIP = new Set(['3.12.1', '3.18.1']);
const tables = [];
let group = '', t = null;
for (const line of data.split('\n')) {
  let m;
  if ((m = line.match(/^### (.+)/))) { group = m[1].trim(); continue; }
  if ((m = line.match(/^\*\*(\d+)\. ([\d.]+) (.+)\*\*$/))) { t = { roll: +m[1], id: m[2], name: m[3], group, members: null, core: '', diffs: [] }; tables.push(t); continue; }
  if (!t) continue;
  if ((m = line.match(/^Members(?: \([^)]*\))?: (.+)/))) {
    // "A; B (detail); C." -> names, keeping the detail as part of the member
    t.members = m[1].replace(/\.$/, '').split(/;\s*/).map(s => s.trim()).filter(Boolean);
    continue;
  }
  if ((m = line.match(/^Core: (.+)/))) { t.core = m[1].trim(); continue; }
  if ((m = line.match(/^\d+\. (.+?): (.+)$/))) t.diffs.push([m[1].trim(), m[2].trim()]);
}
const keep = tables.filter(x => !SKIP.has(x.id)), adult = tables.filter(x => SKIP.has(x.id));
if (tables.length !== 67 || keep.some(x => !x.core || !x.diffs.length)) { console.error('unexpected data:', tables.length, 'tables'); process.exit(1); }
const out = '// Generated by tools/convert_dx.js from the diagnosis-practice-case study data (DSM-5-TR differential tables,\n' +
  '// condensed). Do not edit by hand. Used by the STUDY CASES encounters (src/game/dxcases.js).\n' +
  'G.DX_TABLES = ' + JSON.stringify(keep.map(x => Object.assign({ roll: x.roll, id: x.id, name: x.name, group: x.group }, x.members ? { members: x.members } : {}, { core: x.core, diffs: x.diffs })), null, 0)
    .replace(/\},\{"roll"/g, '},\n{"roll"') + ';\n';
const adultOut = '// Adult-only tables (Sexual Dysfunctions, Paraphilic Disorders): used only with OPTION > ADULT CASES, in a plain\n' +
  '// clinical setting with no theme, adult patients and non-explicit clinical language (the skill\'s rules).\n' +
  'G.DX_ADULT_TABLES = ' + JSON.stringify(adult.map(x => Object.assign({ roll: x.roll, id: x.id, name: x.name, group: x.group, adult: true }, x.members ? { members: x.members } : {}, { core: x.core, diffs: x.diffs })), null, 0)
    .replace(/\},\{"roll"/g, '},\n{"roll"') + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'data', 'dxcases.js'), out + adultOut);
console.log('wrote', keep.length, 'tables,', keep.reduce((n, x) => n + x.diffs.length, 0), 'differentials, and', adult.length, 'adult-only tables');
